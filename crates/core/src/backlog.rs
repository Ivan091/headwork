/// The text after a leading `For you:` or `For you (...):` when it has one; an item written so is the user's.
fn for_you_rest(text: &str) -> Option<&str> {
    let text = text.trim_start();
    let head = text.get(..FOR_YOU.len())?;
    if !head.eq_ignore_ascii_case(FOR_YOU) {
        return None;
    }
    let mut rest = text.get(FOR_YOU.len()..)?.trim_start();
    if rest.starts_with('(') {
        let mut depth = 0_usize;
        let mut end = None;
        for (at, c) in rest.char_indices() {
            match c {
                '(' => depth += 1,
                ')' => {
                    depth = depth.saturating_sub(1);
                    if depth == 0 {
                        end = Some(at);
                        break;
                    }
                }
                _ => {}
            }
        }
        rest = rest.get(end? + 1..)?.trim_start();
    }
    let rest = rest.strip_prefix(':')?.trim();
    (!rest.is_empty()).then_some(rest)
}

/// The text an item is known by: whitespace collapsed to single spaces and a leading `For you:` or `For you (...):`
/// removed, so the same item written by hand or by the export has one identity.
#[must_use]
pub fn identity(text: &str) -> String {
    let collapsed = text.split_whitespace().collect::<Vec<_>>().join(" ");
    for_you_rest(&collapsed).map_or_else(|| collapsed.clone(), str::to_owned)
}

/// A text as the reader of `backlog.md` takes it, so an item added by hand and one imported from the file are the same item.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Normalized {
    /// The text without the groups the fields below came from and without a leading `For you:`.
    pub text: String,
    /// The user, when the text started with `For you:` or `For you (...):`.
    pub owner: Option<BacklogOwner>,
    /// The `(added D)` group.
    pub added: Option<BacklogDate>,
    /// The `(not before D)` group.
    pub not_before: Option<BacklogDate>,
    /// The `(due D)` or `(by D)` group.
    pub due: Option<BacklogDate>,
}

/// Reads `text` the way an import reads an item line: the date groups become fields and a `For you:` prefix becomes the
/// owner.
#[must_use]
pub fn normalize(text: &str) -> Normalized {
    let read = read_body(text, false);
    let (owner, text) = match for_you_rest(&read.text) {
        Some(rest) => (Some(BacklogOwner::User), rest.to_owned()),
        None => (None, read.text),
    };
    Normalized {
        text,
        owner,
        added: read.added,
        not_before: read.not_before,
        due: read.due,
    }
}

fn is_word(c: char) -> bool {
    c.is_alphanumeric() || c == '_'
}

fn skip_space(chars: &[char], mut at: usize) -> usize {
    while chars.get(at).is_some_and(|c| c.is_whitespace()) {
        at += 1;
    }
    at
}

fn date_at(chars: &[char], at: usize) -> Option<BacklogDate> {
    if at > 0 && chars.get(at - 1).is_some_and(char::is_ascii_digit) {
        return None;
    }
    if chars.get(at + 10).is_some_and(char::is_ascii_digit) {
        return None;
    }
    let window: String = chars.get(at..at + 10)?.iter().collect();
    BacklogDate::parse(&window).ok()
}

fn first_date(chars: &[char]) -> Option<BacklogDate> {
    (0..chars.len()).find_map(|at| date_at(chars, at))
}

fn word_at(chars: &[char], at: usize, word: &str) -> bool {
    let want: Vec<char> = word.chars().collect();
    chars.get(at..at + want.len()).is_some_and(|have| {
        have.iter()
            .zip(&want)
            .all(|(a, b)| a.eq_ignore_ascii_case(b))
    }) && !chars.get(at + want.len()).copied().is_some_and(is_word)
}

fn keyword_date(chars: &[char], words: &[&str]) -> Option<BacklogDate> {
    'start: for start in 0..chars.len() {
        if start > 0 && chars.get(start - 1).copied().is_some_and(is_word) {
            continue;
        }
        let mut at = start;
        for (n, word) in words.iter().enumerate() {
            if n > 0 {
                let next = skip_space(chars, at);
                if next == at {
                    continue 'start;
                }
                at = next;
            }
            if !word_at(chars, at, word) {
                continue 'start;
            }
            at += word.chars().count();
        }
        let next = skip_space(chars, at);
        if next == at {
            continue;
        }
        if let Some(date) = date_at(chars, next) {
            return Some(date);
        }
    }
    None
}

fn groups(chars: &[char]) -> Vec<(usize, usize)> {
    let mut found = Vec::new();
    let (mut depth, mut start) = (0_usize, 0_usize);
    for (at, c) in chars.iter().enumerate() {
        match c {
            '(' => {
                if depth == 0 {
                    start = at;
                }
                depth += 1;
            }
            ')' if depth > 0 => {
                depth -= 1;
                if depth == 0 {
                    found.push((start, at));
                }
            }
            _ => {}
        }
    }
    found
}

fn trailing_group(chars: &[char]) -> Option<(usize, usize)> {
    let end = chars.iter().rposition(|c| !c.is_whitespace())?;
    if chars.get(end) != Some(&')') {
        return None;
    }
    let mut depth = 0_usize;
    for at in (0..=end).rev() {
        match chars.get(at)? {
            ')' => depth += 1,
            '(' => {
                depth -= 1;
                if depth == 0 {
                    return Some((at, end));
                }
            }
            _ => {}
        }
    }
    None
}

fn inner(chars: &[char], (start, end): (usize, usize)) -> &[char] {
    chars.get(start + 1..end).unwrap_or_default()
}

fn exact_group(inside: &[char], words: &[&str]) -> Option<BacklogDate> {
    let text: String = inside.iter().collect();
    let tokens: Vec<&str> = text.split_whitespace().collect();
    let (date, head) = tokens.split_last()?;
    if head.len() != words.len()
        || !head
            .iter()
            .zip(words)
            .all(|(a, b)| a.eq_ignore_ascii_case(b))
    {
        return None;
    }
    BacklogDate::parse(date).ok()
}

fn linked_task_group(inside: &[char]) -> bool {
    let text: String = inside.iter().collect();
    let Some(rest) = text.trim().strip_prefix("task ") else {
        return false;
    };
    let name = |name: &str| !name.is_empty() && !name.contains(char::is_whitespace);
    match rest.split_once(", ") {
        Some((task, state)) => name(task) && state.trim().parse::<TaskState>().is_ok(),
        None => name(rest) && rest.contains('-'),
    }
}

struct Closing {
    on: Option<BacklogDate>,
    note: Option<String>,
    cancelled: bool,
}

fn closing_group(inside: &[char]) -> Option<Closing> {
    let start = skip_space(inside, 0);
    let word_len = inside
        .get(start..)?
        .iter()
        .take_while(|c| c.is_alphabetic())
        .count();
    let word: String = inside
        .get(start..start + word_len)?
        .iter()
        .collect::<String>()
        .to_lowercase();
    if !matches!(
        word.as_str(),
        "done" | "dropped" | "cancelled" | "superseded"
    ) {
        return None;
    }
    let rest = inside.get(start + word_len..)?;
    let separator = |at: usize| matches!(rest.get(at), Some(':' | ',' | ';'));
    let mut at = skip_space(rest, 0);
    if separator(at) {
        at = skip_space(rest, at + 1);
    }
    let mut on = None;
    if let Some(date) = date_at(rest, at) {
        on = Some(date);
        at = skip_space(rest, at + 10);
        if separator(at) {
            at += 1;
        }
    }
    let note: String = rest.get(at..).unwrap_or_default().iter().collect();
    let note = note.trim().to_owned();
    Some(Closing {
        on: on.or_else(|| first_date(rest)),
        note: (!note.is_empty()).then_some(note),
        cancelled: word != "done",
    })
}

const IN_PROGRESS: &str = "in progress";
const BLOCKED: &str = "blocked";

/// How a block whose unblock returns to in progress says so in its tag.
const FROM_IN_PROGRESS: &str = ", from in progress";

/// The status tag at the end of an open item's line and the text before it: `[in progress]`, `[in progress: task <name>
/// <state>]` (the task part is ignored), `[blocked: <reason>]`, `[blocked: <reason>: <note>]`, and either blocked form
/// with `, from in progress` after the reason when an unblock returns the item to in progress (else to the backlog).
///
/// Only `[in progress]`, `[in progress: ...]` and `[blocked: ...]` count as tags, so `Collect [in progress reports]` is
/// plain text. `None` when the line ends in no tag; `Some(Err)` names why a tag of those shapes cannot be read.
fn status_tag(body: &str) -> Option<Result<(&str, BacklogStatus), String>> {
    let inner_end = body.strip_suffix(']')?.len();
    let start = [
        format!("[{IN_PROGRESS}]"),
        format!("[{IN_PROGRESS}:"),
        format!("[{BLOCKED}:"),
    ]
    .iter()
    .filter_map(|marker| body.rfind(marker.as_str()))
    .max()?;
    let before = body.get(..start)?;
    if !before.ends_with(char::is_whitespace) {
        return None;
    }
    let inside = body.get(start + 1..inner_end)?;
    let bad = || Err(format!("a status tag that cannot be read: `[{inside}]`"));
    if inside == IN_PROGRESS
        || inside
            .strip_prefix(IN_PROGRESS)
            .is_some_and(|rest| rest.starts_with(": task "))
    {
        return Some(Ok((before.trim_end(), BacklogStatus::InProgress)));
    }
    let Some(rest) = inside
        .strip_prefix(BLOCKED)
        .and_then(|rest| rest.strip_prefix(':'))
    else {
        return Some(bad());
    };
    let (head, note) = rest.split_once(':').unwrap_or((rest, ""));
    let head = head.trim();
    let (word, return_to) = head
        .strip_suffix(FROM_IN_PROGRESS)
        .map_or((head, ReturnTo::Backlog), |word| {
            (word, ReturnTo::InProgress)
        });
    let Ok(reason) = word.trim().parse::<BlockReason>() else {
        return Some(bad());
    };
    let note = note.trim();
    Some(Ok((
        before.trim_end(),
        BacklogStatus::Blocked(Block {
            reason,
            note: (!note.is_empty()).then(|| note.to_owned()),
            before: return_to,
        }),
    )))
}

struct Body {
    text: String,
    status: Option<BacklogStatus>,
    bad_tag: Option<String>,
    added: Option<BacklogDate>,
    not_before: Option<BacklogDate>,
    due: Option<BacklogDate>,
    closing: Option<Closing>,
}

fn read_body(body: &str, closed: bool) -> Body {
    let trimmed = body.trim();
    let (body, status, bad_tag) = match status_tag(trimmed).filter(|_| !closed) {
        Some(Ok((rest, tagged))) => (rest, Some(tagged), None),
        Some(Err(why)) => (trimmed, None, Some(why)),
        None => (trimmed, None, None),
    };
    let mut chars: Vec<char> = body.chars().collect();
    if let Some(group) = trailing_group(&chars)
        && linked_task_group(inner(&chars, group))
    {
        chars.truncate(group.0);
    }
    let mut closing = None;
    if closed && let Some(group) = trailing_group(&chars) {
        closing = closing_group(inner(&chars, group));
        if closing.is_some() {
            chars.truncate(group.0);
        }
    }
    let added = keyword_date(&chars, &["added"]);
    let not_before = keyword_date(&chars, &["not", "before"]);
    let due = keyword_date(&chars, &["due"]).or_else(|| {
        groups(&chars)
            .into_iter()
            .find_map(|group| exact_group(inner(&chars, group), &["by"]))
    });
    let mut kept: Vec<char> = Vec::with_capacity(chars.len());
    let mut from = 0;
    for group in groups(&chars) {
        let inside = inner(&chars, group);
        let exact = exact_group(inside, &["added"]).is_some()
            || exact_group(inside, &["not", "before"]).is_some()
            || exact_group(inside, &["due"]).is_some()
            || exact_group(inside, &["by"]).is_some();
        if exact {
            kept.extend(chars.get(from..group.0).unwrap_or_default());
            while kept.last().is_some_and(|c| c.is_whitespace()) {
                kept.pop();
            }
            from = group.1 + 1;
        }
    }
    kept.extend(chars.get(from..).unwrap_or_default());
    let text: String = kept.into_iter().collect();
    Body {
        text: text.trim().to_owned(),
        status,
        bad_tag,
        added,
        not_before,
        due,
        closing,
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Area {
    Projects,
    Done,
    Cancelled,
}

enum Mark {
    Open,
    Checked,
    Plain,
}

fn heading_area(name: &str) -> Area {
    let lower = name.to_lowercase();
    let word = lower.split_whitespace().next().unwrap_or_default();
    match word {
        "done" => Area::Done,
        "dropped" | "cancelled" => Area::Cancelled,
        _ => Area::Projects,
    }
}

fn usable_heading(name: &str) -> bool {
    let name = name.trim();
    !name.is_empty() && !name.starts_with('#')
}

fn mark_of(rest: &str) -> (Mark, &str) {
    let checked = rest
        .strip_prefix("[x]")
        .or_else(|| rest.strip_prefix("[X]"));
    match (rest.strip_prefix("[ ]"), checked) {
        (Some(body), _) => (Mark::Open, body),
        (None, Some(body)) => (Mark::Checked, body),
        (None, None) => (Mark::Plain, rest),
    }
}

struct Reader {
    items: Vec<BacklogDraft>,
    unparsed: Vec<Unparsed>,
    warnings: Vec<Unparsed>,
    project: String,
    section: Option<String>,
    area: Area,
    intro: bool,
    titled: bool,
    last_item: bool,
}

impl Reader {
    fn skip(&mut self, line_no: usize, line: &str, reason: &str) {
        self.last_item = false;
        self.unparsed.push(Unparsed {
            line_no,
            line: line.to_owned(),
            reason: reason.to_owned(),
        });
    }

    fn area_heading(&mut self, name: &str) {
        self.section = None;
        self.area = heading_area(name);
        if self.area == Area::Projects {
            name.trim().clone_into(&mut self.project);
        } else {
            GENERAL.clone_into(&mut self.project);
        }
    }

    fn item(&mut self, line_no: usize, line: &str, rest: &str) {
        let (mark, body) = mark_of(rest);
        let body = body.trim();
        let status = match (self.area, &mark) {
            (Area::Done, _) | (Area::Projects, Mark::Checked) => Some(BacklogStatus::Done),
            (Area::Cancelled, _) => Some(BacklogStatus::Cancelled),
            (Area::Projects, Mark::Open) => Some(BacklogStatus::Backlog),
            (Area::Projects, Mark::Plain) => None,
        };
        if body.is_empty() {
            self.skip(line_no, line, "an item with no text");
            return;
        }
        let Some(mut status) = status else {
            self.skip(
                line_no,
                line,
                "an item with no checkbox outside the Done and Cancelled sections",
            );
            return;
        };
        let read = read_body(body, status != BacklogStatus::Backlog);
        if let Some(why) = &read.bad_tag {
            self.warnings.push(Unparsed {
                line_no,
                line: line.to_owned(),
                reason: format!("{why}; imported in the backlog with the tag kept in its text"),
            });
        }
        if self.area == Area::Projects
            && read
                .closing
                .as_ref()
                .is_some_and(|closing| closing.cancelled)
        {
            status = BacklogStatus::Cancelled;
        }
        if let Some(tagged) = read.status {
            status = tagged;
        }
        let (owner, text) = match for_you_rest(&read.text) {
            Some(rest) => (BacklogOwner::User, rest.to_owned()),
            None => (BacklogOwner::Agent, read.text),
        };
        let (done_on, done_note) = read
            .closing
            .map_or((None, None), |closing| (closing.on, closing.note));
        self.items.push(BacklogDraft {
            project: self.project.clone(),
            section: self.section.clone(),
            text,
            notes: Vec::new(),
            status,
            owner,
            added: read.added,
            not_before: read.not_before,
            due: read.due,
            done_on,
            done_note,
        });
        self.last_item = true;
    }

    fn note(&mut self, line_no: usize, line: &str) {
        let Some(item) = self.items.last_mut().filter(|_| self.last_item) else {
            self.skip(line_no, line, "a note with no item right above it");
            return;
        };
        let note = clean_note(line);
        if !note.is_empty() {
            item.notes.push(note);
        }
    }

    fn line(&mut self, line_no: usize, line: &str) {
        let trimmed = line.trim();
        if trimmed.is_empty() {
            self.last_item = false;
        } else if let Some(name) = line.strip_prefix("### ") {
            self.intro = false;
            self.last_item = false;
            if usable_heading(name) {
                self.section = Some(name.trim().to_owned());
            } else {
                self.skip(line_no, line, "a heading with no usable name");
            }
        } else if let Some(name) = line.strip_prefix("## ") {
            self.intro = false;
            self.last_item = false;
            if usable_heading(name) {
                self.area_heading(name);
            } else {
                self.skip(line_no, line, "a heading with no usable name");
            }
        } else if line.starts_with("# ") || line == "#" {
            if self.titled {
                self.skip(line_no, line, "a second title heading");
            } else {
                self.titled = true;
                self.intro = true;
                self.last_item = false;
            }
        } else if line.starts_with('#') {
            self.skip(
                line_no,
                line,
                "a heading this reader does not know (only #, ## and ### count)",
            );
        } else if let Some(rest) = line.strip_prefix("- ") {
            self.intro = false;
            self.last_item = false;
            self.item(line_no, line, rest);
        } else if line.starts_with(char::is_whitespace) && trimmed.starts_with("- ") {
            self.note(line_no, line);
        } else if !self.intro {
            self.skip(line_no, line, "not a heading, an item or a note");
        }
    }
}

/// Whether a line read right after an item line is the rest of that item, split off by a stray line break: it is not
/// blank, not a heading, not an item and not an indented note.
fn continues_item(line: &str) -> bool {
    !line.trim().is_empty()
        && !line.starts_with('#')
        && !line.starts_with("- ")
        && !line.starts_with(char::is_whitespace)
}

/// Joins each stray continuation line to the item line above it with one space and reports it with the line it went
/// to, so the item keeps its whole text and the import still shows the join.
fn join_continuations(text: &str) -> (Vec<(usize, String)>, Vec<Unparsed>) {
    let mut lines: Vec<(usize, String)> = Vec::new();
    let mut joined = Vec::new();
    let mut after_item = false;
    for (index, raw) in text.split('\n').enumerate() {
        let line = raw.strip_suffix('\r').unwrap_or(raw);
        let line_no = index + 1;
        match lines.last_mut() {
            Some((item_no, item)) if after_item && continues_item(line) => {
                item.push(' ');
                item.push_str(line.trim());
                joined.push(Unparsed {
                    line_no,
                    line: line.to_owned(),
                    reason: format!(
                        "the rest of the item on line {item_no}, joined to it with a space"
                    ),
                });
            }
            _ => {
                after_item = line.starts_with("- ");
                lines.push((line_no, line.to_owned()));
            }
        }
    }
    (lines, joined)
}

/// Reads the text of a `backlog.md`: `##` headings are projects, `###` headings sections, `- [ ]` and `- [x]` lines items,
/// indented `- ` lines right after an item its notes.
///
/// Lines are split on `\n` only, so a stray `\r` inside a line stays. A plain line right after an item line is the rest
/// of that item (a stray line break): it is joined to the item and reported in [`Parsed::unparsed`] with the reason.
#[must_use]
pub fn parse(text: &str) -> Parsed {
    let mut reader = Reader {
        items: Vec::new(),
        unparsed: Vec::new(),
        warnings: Vec::new(),
        project: GENERAL.to_owned(),
        section: None,
        area: Area::Projects,
        intro: false,
        titled: false,
        last_item: false,
    };
    let (lines, joined) = join_continuations(text);
    for (line_no, line) in &lines {
        reader.line(*line_no, line);
    }
    let mut unparsed = reader.unparsed;
    unparsed.extend(joined);
    unparsed.sort_by_key(|entry| entry.line_no);
    Parsed {
        items: reader.items,
        unparsed,
        warnings: reader.warnings,
    }
}

fn append(out: &mut String, args: fmt::Arguments<'_>) {
    let _infallible = out.write_fmt(args);
}

fn item_line(item: &BacklogItem, done: bool) -> String {
    let draft = &item.draft;
    let mut text = draft.text.clone();
    if draft.owner == BacklogOwner::User {
        text = format!("{FOR_YOU}: {text}");
    }
    let mut line = format!("- [{}] {text}", if done { 'x' } else { ' ' });
    let mentions = |keyword: &str, date: &BacklogDate| text.contains(&format!("{keyword} {date}"));
    if !done {
        if let Some(date) = draft
            .not_before
            .as_ref()
            .filter(|date| !mentions("not before", date))
        {
            append(&mut line, format_args!(" (not before {date})"));
        }
        if let Some(date) = draft
            .due
            .as_ref()
            .filter(|date| !mentions("due", date) && !mentions("by", date))
        {
            append(&mut line, format_args!(" (due {date})"));
        }
    }
    if let Some(date) = draft.added.as_ref().filter(|date| !mentions("added", date)) {
        append(&mut line, format_args!(" (added {date})"));
    }
    if done {
        let closing = match (&draft.done_on, &draft.done_note) {
            (Some(date), Some(note)) => format!("done {date}: {note}"),
            (Some(date), None) => format!("done {date}"),
            (None, Some(note)) => format!("done: {note}"),
            (None, None) => "done".to_owned(),
        };
        append(&mut line, format_args!(" ({closing})"));
    } else {
        match (&draft.status, &item.task) {
            (BacklogStatus::InProgress, Some(task)) => append(
                &mut line,
                format_args!(" [{IN_PROGRESS}: task {} {}]", task.name, task.state),
            ),
            (BacklogStatus::InProgress, None) => {
                append(&mut line, format_args!(" [{IN_PROGRESS}]"));
            }
            (BacklogStatus::Blocked(block), _) => {
                let from = match block.before {
                    ReturnTo::InProgress => FROM_IN_PROGRESS,
                    ReturnTo::Backlog => "",
                };
                match &block.note {
                    Some(note) => append(
                        &mut line,
                        format_args!(" [{BLOCKED}: {}{from}: {note}]", block.reason),
                    ),
                    None => append(
                        &mut line,
                        format_args!(" [{BLOCKED}: {}{from}]", block.reason),
                    ),
                }
            }
            _ => {}
        }
    }
    for note in &draft.notes {
        append(&mut line, format_args!("\n  - {note}"));
    }
    line
}

/// The `backlog.md` the export writes: open items by project and section, each one in progress or blocked with its status
/// tag, then the [`DONE_KEPT`] most recent done items. Cancelled items are left out.
#[must_use]
pub fn render(backlog_items: &[BacklogItem]) -> String {
    let mut open: Vec<&BacklogItem> = backlog_items
        .iter()
        .filter(|item| item.draft.status.is_open())
        .collect();
    open.sort_by_key(|item| item.position);
    let mut order: Vec<&str> = Vec::new();
    for item in &open {
        if item.draft.project != GENERAL && !order.contains(&item.draft.project.as_str()) {
            order.push(&item.draft.project);
        }
    }
    if open.iter().any(|item| item.draft.project == GENERAL) {
        order.push(GENERAL);
    }
    let mut out = format!("# Backlog\n\n{EXPORT_INTRO}\n");
    for project in order {
        append(&mut out, format_args!("\n## {project}\n\n"));
        let of_project: Vec<&&BacklogItem> = open
            .iter()
            .filter(|item| item.draft.project == project)
            .collect();
        for item in of_project
            .iter()
            .filter(|item| item.draft.section.is_none())
        {
            out.push_str(&item_line(item, false));
            out.push('\n');
        }
        let mut sections: BTreeMap<i64, &str> = BTreeMap::new();
        let mut seen: Vec<&str> = Vec::new();
        for item in &of_project {
            if let Some(section) = item.draft.section.as_deref()
                && !seen.contains(&section)
            {
                seen.push(section);
                sections.insert(item.position, section);
            }
        }
        for section in sections.into_values() {
            append(&mut out, format_args!("\n### {section}\n\n"));
            for item in of_project
                .iter()
                .filter(|item| item.draft.section.as_deref() == Some(section))
            {
                out.push_str(&item_line(item, false));
                out.push('\n');
            }
        }
    }
    let mut done: Vec<&BacklogItem> = backlog_items
        .iter()
        .filter(|item| item.draft.status == BacklogStatus::Done)
        .collect();
    done.sort_by(|a, b| {
        let key = |item: &BacklogItem| {
            (
                item.draft.done_on.is_some(),
                item.draft.done_on.clone(),
                item.position,
            )
        };
        key(b).cmp(&key(a))
    });
    done.truncate(DONE_KEPT);
    if !done.is_empty() {
        append(&mut out, format_args!("\n## Done (last {DONE_KEPT})\n\n"));
        for item in done {
            out.push_str(&item_line(item, true));
            out.push('\n');
        }
    }
    out
}

/// What the export knows when it decides whether to write the file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ExportFacts<'a> {
    /// Whether the file was imported, or is one headwork exported itself.
    pub imported: bool,
    /// The hash of the last export's content.
    pub exported_hash: Option<&'a str>,
    /// Whether the file exists.
    pub file_exists: bool,
    /// The hash of the file as it is, when it exists.
    pub on_disk_hash: Option<&'a str>,
    /// The hash of the content to write.
    pub new_hash: &'a str,
}

/// What the export does.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExportPlan {
    /// The content equals the last export; nothing to write.
    Unchanged,
    /// The file exists and was never imported; it is left alone.
    NotImported,
    /// Write the file, after copying it when it is not what the last export wrote.
    Write {
        /// Whether the file on disk is to be copied first.
        back_up: bool,
    },
}

/// Decides an export.
///
/// Nothing is written when the content equals the last export and the file exists (a file edited by hand stays until the
/// store changes), nor to an existing file that was never imported; otherwise the file is written, after a copy of it when
/// it differs from what the last export wrote.
#[must_use]
pub fn plan_export(facts: &ExportFacts<'_>) -> ExportPlan {
    if !facts.file_exists {
        return ExportPlan::Write { back_up: false };
    }
    if facts.exported_hash == Some(facts.new_hash) {
        return ExportPlan::Unchanged;
    }
    if !facts.imported {
        return ExportPlan::NotImported;
    }
    ExportPlan::Write {
        back_up: facts.on_disk_hash != facts.exported_hash,
    }
}

/// The file an export of the configured `[backlog] file` moves the list away from (`docs/backlog.md`, section 9).
///
/// It is the other file most recently exported as the configured one, when `target` never was. `configured` holds each recorded
/// file that was ever exported as the configured one, with when it last was (RFC 3339, UTC). An export to `--file` is
/// never a move, so its caller does not ask.
#[must_use]
pub fn move_source<'a>(target: &str, configured: &[(&'a str, &'a str)]) -> Option<&'a str> {
    if configured.iter().any(|(path, _)| *path == target) {
        return None;
    }
    configured
        .iter()
        .max_by(|(left_path, left_at), (right_path, right_at)| {
            left_at
                .cmp(right_at)
                .then_with(|| right_path.cmp(left_path))
        })
        .map(|(path, _)| *path)
}

/// The one line an earlier backlog file is left holding when the export moved to `new_path` and `[backlog] leave_pointer`
/// is on (`docs/backlog.md`, section 9).
#[must_use]
pub fn pointer_line(new_path: &str) -> String {
    format!(
        "Moved: the backlog is now {new_path}, generated by headwork from its store (`headwork backlog`).\n"
    )
}

/// How many items an exploration may still add: the `picked` count of its newest `Backlog` answer minus the `added`
/// items it logged since, never below 0.
#[must_use]
pub const fn adds_left(picked: u64, added: u64) -> u64 {
    picked.saturating_sub(added)
}

