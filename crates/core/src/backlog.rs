const FOR_YOU: &str = "For you";

/// A backlog item or date that cannot be used.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum BacklogError {
    /// The text is not a calendar date written `YYYY-MM-DD`.
    #[error("`{0}` is not a date written YYYY-MM-DD")]
    BadDate(String),
    /// A field of an item cannot be written to `backlog.md` as it is.
    #[error("the {field} {problem}")]
    Invalid {
        /// The field: `text`, `project`, `section` or `note`.
        field: &'static str,
        /// What is wrong with it.
        problem: &'static str,
    },
}

const fn invalid(field: &'static str, problem: &'static str) -> BacklogError {
    BacklogError::Invalid { field, problem }
}

/// A calendar date, `YYYY-MM-DD`.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct BacklogDate(String);

impl BacklogDate {
    /// The date written `text`.
    ///
    /// # Errors
    ///
    /// Returns [`BacklogError::BadDate`] unless `text` is a real calendar date with a four-digit year.
    pub fn parse(text: &str) -> Result<Self, BacklogError> {
        let bad = || BacklogError::BadDate(text.to_owned());
        let parts: Vec<&str> = text.split('-').collect();
        let [year, month, day] = parts.as_slice() else {
            return Err(bad());
        };
        let digits = |part: &str, len: usize| {
            part.len() == len && part.bytes().all(|byte| byte.is_ascii_digit())
        };
        if !digits(year, 4) || !digits(month, 2) || !digits(day, 2) {
            return Err(bad());
        }
        let year: u32 = year.parse().map_err(|_| bad())?;
        let month: u32 = month.parse().map_err(|_| bad())?;
        let day: u32 = day.parse().map_err(|_| bad())?;
        let leap =
            year.is_multiple_of(4) && (!year.is_multiple_of(100) || year.is_multiple_of(400));
        let longest = match month {
            1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
            4 | 6 | 9 | 11 => 30,
            2 if leap => 29,
            2 => 28,
            _ => return Err(bad()),
        };
        if day == 0 || day > longest {
            return Err(bad());
        }
        Ok(Self(text.to_owned()))
    }

    /// The date as `YYYY-MM-DD`.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for BacklogDate {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl FromStr for BacklogDate {
    type Err = BacklogError;

    fn from_str(text: &str) -> Result<Self, Self::Err> {
        Self::parse(text)
    }
}

impl TryFrom<String> for BacklogDate {
    type Error = BacklogError;

    fn try_from(text: String) -> Result<Self, Self::Error> {
        Self::parse(&text)
    }
}

impl From<BacklogDate> for String {
    fn from(date: BacklogDate) -> Self {
        date.0
    }
}

