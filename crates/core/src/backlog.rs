/// An item to add: everything a row holds that the store does not decide.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct BacklogDraft {
    /// The area heading: `me-sim`, `headwork`, `Setup`; [`GENERAL`] outside every heading.
    pub project: String,
    /// A `###` subheading under the project.
    pub section: Option<String>,
    /// The item, without checkbox, the groups the fields below came from, and the trailing done group.
    pub text: String,
    /// The indented sub-bullets, one per line.
    pub notes: Vec<String>,
    /// Where it stands, with its block when blocked.
    #[serde(flatten)]
    pub status: BacklogStatus,
    /// Who has to act.
    pub owner: BacklogOwner,
    /// The day it was added.
    pub added: Option<BacklogDate>,
    /// The first day it may start.
    pub not_before: Option<BacklogDate>,
    /// The day it is due.
    pub due: Option<BacklogDate>,
    /// The day it was done or cancelled.
    pub done_on: Option<BacklogDate>,
    /// What was said when it was done or cancelled.
    pub done_note: Option<String>,
}

impl BacklogDraft {
    /// Checks that every field can be written to `backlog.md` and read back as it is.
    ///
    /// # Errors
    ///
    /// Returns [`BacklogError::Invalid`] naming the field: a text that is empty, runs over several lines or starts with
    /// `For you:` (the owner says that); a project that is empty, runs over several lines, starts with `#` or whose first
    /// word is Done, Cancelled or Dropped (those headings hold finished items); a section that is empty, runs over several lines or
    /// starts with `#`; a note that is empty or runs over several lines.
    pub fn validate(&self) -> Result<(), BacklogError> {
        if self.text.trim().is_empty() {
            return Err(invalid("text", "is empty"));
        }
        if self.text.contains('\n') {
            return Err(invalid("text", "must be one line"));
        }
        if for_you_rest(&self.text).is_some() {
            return Err(invalid(
                "text",
                "must not start with `For you:`; set the owner instead",
            ));
        }
        check_heading("project", &self.project)?;
        let first = self
            .project
            .split_whitespace()
            .next()
            .unwrap_or_default()
            .to_lowercase();
        if matches!(first.as_str(), "done" | "dropped" | "cancelled") {
            return Err(invalid(
                "project",
                "must not start with Done, Cancelled or Dropped: those headings hold finished items",
            ));
        }
        if let Some(section) = &self.section {
            check_heading("section", section)?;
        }
        for note in &self.notes {
            if note.trim().is_empty() {
                return Err(invalid("note", "is empty"));
            }
            if note.contains('\n') {
                return Err(invalid("note", "must be one line"));
            }
        }
        Ok(())
    }
}

fn check_heading(field: &'static str, name: &str) -> Result<(), BacklogError> {
    if name.trim().is_empty() {
        Err(invalid(field, "is empty"))
    } else if name.contains('\n') {
        Err(invalid(field, "must be one line"))
    } else if name.trim_start().starts_with('#') {
        Err(invalid(field, "must not start with `#`"))
    } else {
        Ok(())
    }
}

/// The longest text an automatic item takes from a brief.
const GOAL_CHARS: usize = 160;

/// The goal line of a brief: its first line with words, without markdown marks, a leading `Goal:`, brackets, and cut to
/// 160 characters; `None` for a brief with no words.
#[must_use]
pub fn goal_line(brief: &str) -> Option<String> {
    let line = brief
        .lines()
        .map(|line| {
            line.trim_start_matches(['#', '-', '*', '>', ' ', '\t'])
                .trim()
        })
        .find(|line| !line.is_empty())?;
    let line = line
        .get(..5)
        .filter(|head| head.eq_ignore_ascii_case("goal:"))
        .and_then(|_| line.get(5..))
        .unwrap_or(line);
    let clean: String = line.chars().filter(|c| !matches!(c, '[' | ']')).collect();
    let clean = clean.split_whitespace().collect::<Vec<_>>().join(" ");
    if clean.is_empty() {
        None
    } else {
        Some(clean.chars().take(GOAL_CHARS).collect())
    }
}

/// A note as it is kept: trimmed, without a leading `- `.
#[must_use]
pub fn clean_note(note: &str) -> String {
    note.trim().trim_start_matches("- ").trim().to_owned()
}

