    fn row(id: i64, draft: &TodoDraft) -> Todo {
        Todo {
            id,
            project: draft.project.clone(),
            section: draft.section.clone(),
            text: draft.text.clone(),
            notes: draft.notes.clone(),
            state: draft.state,
            owner: draft.owner,
            added: draft.added.clone(),
            not_before: draft.not_before.clone(),
            due: draft.due.clone(),
            done_on: draft.done_on.clone(),
            done_note: draft.done_note.clone(),
            task: None,
            position: id,
        }
    }

    #[test]
    fn render_then_parse_gives_back_text_state_owner_and_dates() {
        let source = concat!(
            "# To-do\n\n## me-sim\n\n",
            "- [ ] For you: pay (not before 2026-12-01) (due 2026-12-24) (added 2026-11-02)\n  - a note\n",
            "- [ ] Plain (audit, added 2026-11-17; more)\n\n### Audit\n\n- [ ] In a section (added 2026-11-03)\n\n",
            "## Setup\n\n- [ ] Third\n\n## Done\n\n- [x] Shipped (added 2026-11-01) (done 2026-11-09: PR #5)\n",
            "- [x] Early (done)\n",
        );
        let first = parse(source);
        assert!(first.unparsed.is_empty(), "{:?}", first.unparsed);
        let rows: Vec<Todo> = first
            .items
            .iter()
            .zip(1..)
            .map(|(draft, id)| row(id, draft))
            .collect();
        let written = render(&rows);
        let second = parse(&written);
        assert!(
            second.unparsed.is_empty(),
            "{:?}\n{written}",
            second.unparsed
        );
        assert_eq!(second.items.len(), first.items.len(), "{written}");
        for (before, after) in first.items.iter().zip(&second.items) {
            assert_eq!(before.text, after.text, "text");
            assert_eq!(before.state, after.state, "state of {}", before.text);
            assert_eq!(before.owner, after.owner, "owner of {}", before.text);
            assert_eq!(
                (
                    &before.added,
                    &before.not_before,
                    &before.due,
                    &before.done_on
                ),
                (&after.added, &after.not_before, &after.due, &after.done_on),
                "dates of {}",
                before.text
            );
            assert_eq!(before.notes, after.notes, "notes of {}", before.text);
        }
        assert_eq!(render(&rows), written, "the render is stable");
    }

    #[test]
    fn a_linked_open_item_survives_the_round_trip_and_dropped_ones_are_not_written() {
        let drafts = parse("## p\n\n- [ ] Linked item\n- [ ] Gone\n").items;
        let mut rows: Vec<Todo> = drafts
            .iter()
            .zip(1..)
            .map(|(draft, id)| row(id, draft))
            .collect();
        if let Some(first) = rows.first_mut() {
            first.task = Some(LinkedTask {
                id: 4,
                name: "headwork-linked".to_owned(),
                state: "working".to_owned(),
            });
        }
        if let Some(second) = rows.get_mut(1) {
            second.state = TodoState::Dropped;
        }
        let written = render(&rows);
        assert!(
            written.contains("- [ ] Linked item (task headwork-linked, working)"),
            "{written}"
        );
        assert!(!written.contains("Gone"), "{written}");
        let back = parse(&written);
        assert_eq!(
            back.items.first().map(|item| item.text.as_str()),
            Some("Linked item")
        );
    }

    #[test]
    fn the_done_section_keeps_the_newest_twenty() {
        let drafts: Vec<TodoDraft> = (1..=25)
            .map(|day| {
                let mut draft = parse("## p\n\n- [x] item\n").items.remove(0);
                draft.text = format!("item {day}");
                draft.done_on = TodoDate::parse(&format!("2026-11-{day:02}")).ok();
                draft
            })
            .collect();
        let rows: Vec<Todo> = drafts
            .iter()
            .zip(1..)
            .map(|(draft, id)| row(id, draft))
            .collect();
        let written = render(&rows);
        assert_eq!(written.matches("- [x]").count(), DONE_KEPT, "{written}");
        assert!(written.contains("item 25"), "newest kept");
        assert!(!written.contains("item 5 "), "oldest left out");
        assert!(
            written.find("item 25").unwrap_or(0) < written.find("item 24").unwrap_or(0),
            "newest first"
        );
    }
